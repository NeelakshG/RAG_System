def _export_secrets_to_env() -> None:
    """Streamlit Community Cloud stores settings in st.secrets. Copy the
    top-level string values into the environment so Config (which reads
    RAG_* env vars) picks them up. Real env vars win. No secrets file
    (the normal local setup) is fine."""
    try:
        secrets = dict(st.secrets)
    except Exception:
        return
    for key, value in secrets.items():
        if isinstance(value, (str, int, float, bool)) and key not in os.environ:
            os.environ[key] = str(value)



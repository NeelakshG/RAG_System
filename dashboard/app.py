IS_DEMO = BACKEND_MODE == "embedded"


@st.cache_resource(show_spinner="Loading models and indexing the demo documents (first visit only)...")
def get_backend(mode: str):
    """One backend per server process, shared by every visitor. `mode` is
    part of the cache key, so changing RAG_DASHBOARD_BACKEND in the app's
    secrets takes effect without a reboot."""
    if mode == "embedded":
        from config import Config

        service = build_embedded_service(REPO_ROOT)
        return EmbeddedBackend(
            service,
            max_new_questions_per_minute=Config().demo_new_questions_per_minute,
            seed_answers=load_seed_answers(),
        )
    return ApiBackend(
        os.environ.get("API_BASE_URL", "http://localhost:8000"),
        # Sent on write endpoints. Lives only on the dashboard's server side,
        # so visitors never see it.
        api_key=os.environ.get("RAG_API_KEY") or None,
    )


def questions_per_session() -> int:
    from config import Config

